#!/usr/bin/env python3
"""从统一资源生成中文表和 18px 单色子集；字体文件只用于构建。"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("font", type=Path)
args = parser.parse_args()
resources = json.loads((root / "assets/redguard/text.json").read_text())
font = ImageFont.truetype(str(args.font), 18)
font.set_variation_by_axes([500])
chars = sorted(set(''.join(resources.values())) | set(chr(i) for i in range(32, 127)))
dest = root / "esp32_marauder"
keys = ',\n  '.join(resources)
(dest / "RedGuardText.h").write_text('''// Generated by tools/generate_redguard_font.py. Do not edit.
#pragma once
#include <stdint.h>
namespace RedGuard {
enum class TextId : uint8_t {
  ''' + keys + ''', Count
};
const char* text(TextId id);
struct Glyph { uint32_t codepoint; uint8_t advance; uint8_t bitmap[72]; };
const Glyph& glyph(uint32_t codepoint);
}
''')
lines = ['// Generated subset of Noto Sans SC; see assets/redguard/OFL.txt.', '#include "RedGuardText.h"', 'namespace RedGuard {', 'static const char* const strings[] = {']
for value in resources.values():
    lines.append('  ' + json.dumps(value, ensure_ascii=False) + ',')
lines += ['};', 'const char* text(TextId id) {', '  unsigned i = static_cast<unsigned>(id);', '  return i < static_cast<unsigned>(TextId::Count) ? strings[i] : "?";', '}', 'static const Glyph glyphs[] = {']
widths = {}
for char in chars:
    image = Image.new('1', (20, 24))
    ImageDraw.Draw(image).text((0, 20), char, font=font, fill=1, anchor='ls')
    packed = []
    for y in range(24):
        for byte in range(3):
            value = 0
            for bit in range(8):
                x = byte * 8 + bit
                if x < 20 and image.getpixel((x, y)): value |= 0x80 >> bit
            packed.append(value)
    advance = max(1, round(font.getlength(char)))
    assert advance <= 20
    widths[char] = advance
    lines.append('  {' + str(ord(char)) + ', ' + str(advance) + ', {' + ','.join(map(str, packed)) + '}},')
lines += ['};', 'const Glyph& glyph(uint32_t cp) {', '  unsigned lo = 0, hi = sizeof(glyphs) / sizeof(glyphs[0]);', '  while (lo < hi) { unsigned mid = lo + (hi - lo) / 2;', '    if (glyphs[mid].codepoint < cp) lo = mid + 1; else hi = mid;', '  }', '  if (lo < sizeof(glyphs)/sizeof(glyphs[0]) && glyphs[lo].codepoint == cp) return glyphs[lo];', '  return glyphs[' + str(chars.index('?')) + '];', '}', '}']
(dest / 'RedGuardText.cpp').write_text('\n'.join(lines) + '\n')
(root / 'assets/redguard/font-manifest.json').write_text(json.dumps({'source': 'https://github.com/google/fonts/tree/main/ofl/notosanssc', 'font_sha256': hashlib.sha256(args.font.read_bytes()).hexdigest(), 'pillow_version': __import__('PIL').__version__, 'pixel_size': 18, 'weight': 500, 'cell': [20, 24], 'glyph_count': len(chars), 'bitmap_bytes': len(chars) * 72, 'chars': ''.join(chars), 'text_widths': {key: sum(widths[c] for c in value) for key, value in resources.items()}}, ensure_ascii=False, indent=2))
print(f'{len(chars)} glyphs, {len(chars) * 72} bitmap bytes')
